import { describe, expect, it } from "bun:test";
import {
  assertTestOnly,
  evaluatePullPolicy,
  generatedMarkerReason,
  isTestPath,
  parsePullPolicy,
  PolicyError,
  policyBlocked,
  testPathProblem,
} from "../src/policy";

describe("testPathProblem", () => {
  it("allows test files and files inside test directories", () => {
    for (const path of [
      "src/a.test.ts",
      "src/a.spec.tsx",
      "tests/api/openapi.contract.test.ts",
      "tests/helpers.ts",
      "__tests__/a.ts",
      "test/setup.ts",
      "e2e/login.spec.js",
    ]) {
      expect(testPathProblem(path)).toBeUndefined();
      expect(isTestPath(path)).toBe(true);
    }
  });

  it("rejects source, generated, declaration and lockfile paths", () => {
    for (const path of [
      "src/a.ts",
      "dist/a.test.ts",
      "build/a.spec.ts",
      "coverage/a.test.ts",
      "vendor/a.spec.ts",
      "migrations/001.test.ts",
      "node_modules/a/a.test.ts",
      "src/types.d.ts",
      "bun.lock",
      "package-lock.json",
    ]) {
      expect(testPathProblem(path)).toBeDefined();
      expect(isTestPath(path)).toBe(false);
    }
  });

  it("rejects paths that escape the repository or use the wrong separator", () => {
    for (const path of [
      "",
      "../a.test.ts",
      "src/../a.test.ts",
      "/etc/passwd.test.ts",
      "C:\\repo\\a.test.ts",
      "src\\a.test.ts",
    ]) {
      expect(testPathProblem(path)).toBeDefined();
    }
  });
});

describe("generatedMarkerReason", () => {
  it("reads a generated marker from a comment header", () => {
    for (const source of [
      "// @generated by codegen\nexport const a = 1;",
      "/* DO NOT EDIT */\nexport const a = 1;",
      "# DO NOT EDIT\nexport const a = 1;",
    ]) {
      expect(generatedMarkerReason(source)).toBeDefined();
    }
  });

  it("ignores a mention inside code", () => {
    expect(generatedMarkerReason('const note = "@generated";')).toBeUndefined();
    expect(generatedMarkerReason("export const a = 1;")).toBeUndefined();
  });
});

describe("assertTestOnly", () => {
  it("names the path and the reason it refuses", () => {
    expect(() => assertTestOnly("src/a.ts")).toThrow(PolicyError);
    try {
      assertTestOnly("src/a.ts");
    } catch (error) {
      expect(error).toBeInstanceOf(PolicyError);
      expect((error as PolicyError).path).toBe("src/a.ts");
      expect((error as Error).message).toContain("only test files");
    }
  });

  it("accepts a test artifact", () => {
    expect(() => assertTestOnly("tests/a.test.ts")).not.toThrow();
  });
});

describe("parsePullPolicy", () => {
  it("keeps known fields, ignores unknown ones and treats zero as no gate", () => {
    expect(
      parsePullPolicy({
        killSwitch: true,
        unknown: "ignored",
        maxFiles: 0,
        minCoverageDelta: 0,
        allowedPaths: [" tests/** ", ""],
        labels: ["tests"],
      }),
    ).toEqual({
      killSwitch: true,
      allowedPaths: ["tests/**"],
      labels: ["tests"],
    });
  });

  it("clamps numbers and caps lists", () => {
    const policy = parsePullPolicy({
      maxFiles: 999,
      minCoverageDelta: 9_999_999,
      labels: Array.from({ length: 30 }, (_, index) => `l${index}`),
    });
    expect(policy.maxFiles).toBe(100);
    expect(policy.minCoverageDelta).toBe(1_000_000);
    expect(policy.labels).toHaveLength(20);
  });
});

describe("evaluatePullPolicy", () => {
  const files = [
    {
      path: "src/a.test.ts",
      coverage: { status: "measured", lines: { delta: 2 } },
    },
  ];

  it("allows a pull request that satisfies the gates", () => {
    expect(
      evaluatePullPolicy(
        {
          draftOnly: true,
          maxFiles: 2,
          allowedPaths: ["src/**"],
          minCoverageDelta: 2,
        },
        { files, draft: true },
      ),
    ).toEqual([]);
  });

  it("names every gate that blocks, with a readable message", () => {
    const violations = evaluatePullPolicy(
      {
        killSwitch: true,
        draftOnly: true,
        maxFiles: 1,
        allowedPaths: ["tests/**"],
        minCoverageDelta: 5,
      },
      { files, draft: false },
    );
    expect(violations.map((violation) => violation.gate)).toEqual([
      "kill-switch",
      "draft-only",
      "allowed-paths",
      "coverage-delta",
    ]);
    expect(policyBlocked(violations)).toContain("kill-switch");
    expect(policyBlocked(violations)).toContain("below the required 5");
  });

  it("matches a recursive glob at the top level and below it", () => {
    const policy = { allowedPaths: ["src/**/*.test.ts"] };
    expect(
      evaluatePullPolicy(policy, {
        files: [{ path: "src/a.test.ts" }, { path: "src/deep/b.test.ts" }],
      }),
    ).toEqual([]);
    expect(evaluatePullPolicy(policy, { files: [{ path: "src/a.ts" }] })[0]?.gate).toBe(
      "allowed-paths",
    );
  });

  it("blocks a coverage floor that was never measured", () => {
    const violations = evaluatePullPolicy(
      { minCoverageDelta: 1 },
      {
        files: [{ path: "src/a.test.ts", coverage: { status: "not-measured" } }],
      },
    );
    expect(violations[0]).toMatchObject({ gate: "coverage-delta" });
    expect(violations[0]?.message).toContain("not measured");
  });
});
